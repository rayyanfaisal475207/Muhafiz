"""Validate the reviewed synthetic discovery fixture against an isolated database.

The proposal must have been generated by evidence_catalog.py. This is an
experiment fixture, not a runtime domain mapping or a release acceptance score.
"""
import argparse
import asyncio
import json
import sys
import time
from decimal import Decimal
from pathlib import Path
from urllib.parse import urlsplit
from uuid import uuid4

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from dotenv import load_dotenv
from src.evidence import database
from src.evidence.catalog import SchemaProposal,import_bound_record,publish_bindings
from src.evidence.ingestion import put_document
from src.evidence.runtime import Runtime
from src.evidence.store import ScopedStore
from src.evidence.types import Scope


async def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--proposal',type=Path,required=True)
    parser.add_argument('--records',type=Path,required=True)
    parser.add_argument('--output-dir',type=Path,required=True)
    args=parser.parse_args()
    load_dotenv(ROOT/'.env',override=True)
    load_dotenv(ROOT/'.env.evidence-test',override=True)
    if not urlsplit(database.dsn('ingest')).path.startswith('/muhafiz_evidence_test_'):
        raise RuntimeError('This fixture may only write to the isolated test database')
    bundle=json.loads(args.proposal.read_text(encoding='utf-8'))
    records=json.loads(args.records.read_text(encoding='utf-8'))
    # Independent checks against this fixture's documented meaning. These
    # checks intentionally cannot review arbitrary real source definitions.
    docs=bundle['documentation']
    required=['Each record is one sensor notification observation',
              'record_id is a source-record identifier, not a person identifier or quantity',
              'lag_seconds is the observed elapsed time between sensor detection and notification, measured in seconds']
    if not all(text in docs for text in required): raise ValueError('Not the reviewed synthetic fixture')
    proposal=SchemaProposal.model_validate(bundle['proposal'])
    fields={field.pointer:field for field in proposal.fields}
    if set(fields)!={'/record_id','/lag_seconds'}: raise ValueError('Unexpected model bindings require further review')
    if fields['/record_id'].transform!='text' or fields['/lag_seconds'].transform!='number' or fields['/lag_seconds'].unit!='seconds':
        raise ValueError('The proposed typed meanings disagree with source documentation')
    if any(field.evidence_quote not in docs for field in fields.values()): raise ValueError('Unsupported binding')
    for field in fields.values():
        if field.uncertainty not in (None,'','No uncertainty'): raise ValueError('Unresolved model uncertainty')
        field.uncertainty=None
    namespace='synthetic-catalog-'+uuid4().hex
    scope=Scope(user_id=uuid4(),session_id=uuid4(),case_ids=[namespace],include_global=False)
    args.output_dir.mkdir(parents=True,exist_ok=False)
    review={'reviewer':'Codex independent source-document fixture review',
            'basis':'Typed source definitions and original numeric fixture, separate from proposing GPU model',
            'decisions':{'__entity__':True,'/record_id':True,'/lag_seconds':True},
            'resolved_uncertainty':'Model wrote No uncertainty; source review found no unresolved ambiguity',
            'proposal':proposal.model_dump(),'source_proposal':str(args.proposal),'namespace':namespace}
    (args.output_dir/'review.json').write_text(json.dumps(review,ensure_ascii=False,indent=2),encoding='utf-8')
    try:
        pool=await database.pool('ingest')
        async with pool.acquire() as conn:
            async with conn.transaction():
                doc=await put_document(conn,source_key=namespace+':definitions',text=docs,case_ids=scope.case_ids)
                promoted=await publish_bindings(conn,document_id=doc,namespace=namespace,profile=bundle['profile'],
                    proposal=proposal,documentation=docs,reviewer=review['reviewer'],decisions=review['decisions'])
                bindings=await conn.fetch('SELECT * FROM evidence.source_bindings WHERE profile_id=$1',promoted['profile_id'])
                for record in records:
                    await import_bound_record(conn,namespace=namespace,record_key=record['record_id'],record=record,
                        schema_fingerprint=bundle['profile']['schema_fingerprint'],bindings=bindings,case_ids=scope.case_ids)
        started=time.monotonic()
        answer=await Runtime(ScopedStore(scope)).run(uuid4(),
            'What is the average observed lag time between sensor detection and notification in these sensor observations?',
            scope,deadline=time.monotonic()+90)
        (args.output_dir/'answer.json').write_text(json.dumps(answer.model_dump(mode='json'),ensure_ascii=False,indent=2),encoding='utf-8')
        values=[result.rows[claim.row_index].get(claim.field) for claim in answer.claims
                for result in answer.results if result.result_id==claim.result_id]
        summary={'status':answer.status,'seconds':round(time.monotonic()-started,1),'published':promoted['published'],
                 'checked_values':values,'expected_average':10,'scope':scope.model_dump(mode='json'),
                 'passed':answer.status=='answered' and len(values)==1 and Decimal(str(values[0]))==10}
        (args.output_dir/'summary.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps(summary))
        return 0 if summary['passed'] else 1
    finally: await database.close()


if __name__=='__main__': raise SystemExit(asyncio.run(main()))
